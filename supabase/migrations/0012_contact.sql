-- もぐもGO マイグレーション 0012（お問い合わせ）
--
-- 決まり（設計 docs/superpowers/specs/2026-11-17-settings-legal-contact-design.md）:
--   - アプリの中のフォームから送ると、表 inquiries に 1 行入る。運営は Table Editor で読む。
--   - 送れるのはログイン中の本人だけ（関数 send_inquiry。auth.uid() だけを見る）。アプリからは読めない。
--   - 返事の宛先として、ログインのメールを関数が auth から写す。
--   - 1 人 24 時間に 5 件まで。
--   - 退会しても行は残る（user_id は空になる）。対応後 1 年で運営が消す（プライバシーポリシー）。
-- 適用: 0011 のあとに、Supabase SQL Editor に全体を貼って Run する（何度流しても同じ結果）。
--
-- 運営の使い方（Table Editor の inquiries）:
--   新しいものは status = 'new'。返事をしたら status を 'done' にし、note にメモを書く。
--   返事は reply_to のメールに、運営のメールから送る。
--
-- 手で確かめる（開発用の SQL Editor。:u は自分の user_id）:
--   select set_config('request.jwt.claims', json_build_object('sub', ':u', 'role', 'authenticated')::text, false);
--   select public.send_inquiry('bug', 'テストです', '0.1.0', 'test');   → ok
--   select * from public.inquiries order by created_at desc limit 1;   → reply_to に自分のメール
--   6 回続けて送る                                                       → 6 回目は too_many
--   後片付け: delete from public.inquiries where user_id = ':u';
-- =============================================================================

create table if not exists public.inquiries (
  inquiry_id  bigint      generated by default as identity primary key,
  user_id     uuid        null references auth.users (id) on delete set null,
  reply_to    text        null,
  category    text        not null check (category in ('bug', 'question', 'request', 'account', 'other')),
  body        text        not null check (char_length(body) between 1 and 2000),
  app_version text        not null default '' check (char_length(app_version) <= 60),
  device      text        not null default '' check (char_length(device) <= 300),
  status      text        not null default 'new' check (status in ('new', 'done')),
  note        text        null,
  created_at  timestamptz not null default now()
);

create index if not exists inquiries_user_created_idx on public.inquiries (user_id, created_at desc);

alter table public.inquiries enable row level security;
revoke all on table public.inquiries from public, anon, authenticated;
grant select, insert, update, delete on table public.inquiries to service_role;

-- 返す: 'ok' / 'too_many'（24 時間に 5 件を超えた）/ 'bad'（種類か本文が決まりに合わない）
create or replace function public.send_inquiry(p_category text, p_body text, p_app_version text, p_device text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_body text := btrim(coalesce(p_body, ''));
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;
  if p_category is null or p_category not in ('bug', 'question', 'request', 'account', 'other')
     or char_length(v_body) not between 1 and 2000 then
    return 'bad';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('inquiry:' || v_user::text, 0));
  if (select count(*) from public.inquiries i
       where i.user_id = v_user and i.created_at > now() - interval '24 hours') >= 5 then
    return 'too_many';
  end if;

  insert into public.inquiries (user_id, reply_to, category, body, app_version, device)
  values (
    v_user,
    (select u.email from auth.users u where u.id = v_user),
    p_category,
    v_body,
    left(coalesce(p_app_version, ''), 60),
    left(coalesce(p_device, ''), 300)
  );
  return 'ok';
end;
$$;

revoke all on function public.send_inquiry(text, text, text, text) from public, anon;
grant execute on function public.send_inquiry(text, text, text, text) to authenticated, service_role;
