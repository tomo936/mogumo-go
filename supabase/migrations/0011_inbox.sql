-- =============================================================================
-- もぐもGO マイグレーション 0011（お知らせ・プレゼント A7）
--
-- 決まり（設計 docs/superpowers/specs/2026-11-17-inbox-design.md）:
--   - 運営は Supabase の Table Editor で notices / presents に 1 行足す。アプリは関数だけを通して読む。
--   - プレゼントはグルメコインだけ（1〜10000 枚）。user_id が空なら全員、入っていればその人だけ。期限 expires_at まで。
--   - 受け取りは claim_present で 1 人 1 回だけ。コインは coin_ledger に reason = 'present' で、記録と同じトランザクションで書く。
--   - 関数は auth.uid() だけを見る（ほかの人の分は読めない・受け取れない）。anon は使えない。
-- 適用: 0010 のあとに、Supabase SQL Editor に全体を貼って Run する（何度流しても同じ結果）。
--
-- -----------------------------------------------------------------------------
-- 運営の使い方（Table Editor）
--   お知らせ: notices に Insert row。title と body を書く。starts_at（出し始め）は空なら今から、ends_at は空なら出しっぱなし。
--   プレゼント: presents に Insert row。title・message・coins を書く。
--     全員に配る → user_id は空のまま。1 人に配る → Authentication > Users のその人の UID を user_id に貼る。
--     expires_at は空なら 30 日後。
--   取り下げ: お知らせは ends_at を過去にする。プレゼントは expires_at を過去にする（受け取った分のコインは残る）。
--
-- 手で確かめる（開発用 mogumo-go-dev の SQL Editor。:u は自分の user_id）。
--   select set_config('request.jwt.claims', json_build_object('sub', ':u', 'role', 'authenticated')::text, false);
--   1. insert into public.notices (title, body) values ('テスト', 'こんにちは');
--      select * from public.my_notices();                      → 1 行
--   2. insert into public.presents (title, message, coins) values ('おわび', 'ごめんね', 100) returning present_id;  → :p
--      select * from public.my_presents();                     → claimed false
--   3. select * from public.claim_present(:p);                 → 100, 'ok'
--      もう 1 回                                               → 0, 'already'
--   4. select * from public.my_presents();                     → claimed true
--   後片付け: delete from public.coin_ledger where user_id = ':u' and reason = 'present';
--            delete from public.presents; delete from public.notices;
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. 表
-- -----------------------------------------------------------------------------
create table if not exists public.notices (
  notice_id  bigint      generated by default as identity primary key,
  title      text        not null check (char_length(title) between 1 and 60),
  body       text        not null default '' check (char_length(body) <= 2000),
  starts_at  timestamptz not null default now(),
  ends_at    timestamptz null,
  created_at timestamptz not null default now()
);

create table if not exists public.presents (
  present_id bigint      generated by default as identity primary key,
  user_id    uuid        null references public.profiles (user_id) on delete cascade, -- 空 = 全員
  title      text        not null check (char_length(title) between 1 and 60),
  message    text        not null default '' check (char_length(message) <= 500),
  coins      integer     not null check (coins between 1 and 10000),
  starts_at  timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 days'),
  created_at timestamptz not null default now()
);

create table if not exists public.present_claims (
  present_id bigint      not null references public.presents (present_id) on delete cascade,
  user_id    uuid        not null references public.profiles (user_id) on delete cascade,
  claimed_at timestamptz not null default now(),
  primary key (present_id, user_id)
);

alter table public.notices enable row level security;
alter table public.presents enable row level security;
alter table public.present_claims enable row level security;

-- アプリからは直接読み書きさせない（関数だけ）。Table Editor は RLS の外なので運営は書ける
revoke all on table public.notices, public.presents, public.present_claims from public, anon, authenticated;
grant select, insert, update, delete on table public.notices, public.presents, public.present_claims to service_role;

-- -----------------------------------------------------------------------------
-- 2. coin_ledger に 'present' を足す（理由・金額の check を付けかえ、参照の列を足す）
--   受け取ったコインを残すため、受け取られたプレゼントの行は消せない（on delete restrict）
-- -----------------------------------------------------------------------------
alter table public.coin_ledger add column if not exists present_id bigint null
  references public.presents (present_id) on delete restrict;

alter table public.coin_ledger drop constraint if exists coin_ledger_reason_check;
alter table public.coin_ledger add constraint coin_ledger_reason_check
  check (reason in ('checkin', 'hint_bonus', 'weekly_mission', 'town_conquest', 'gacha', 'login_bonus', 'present'));

alter table public.coin_ledger drop constraint if exists coin_ledger_amount_check;
alter table public.coin_ledger add constraint coin_ledger_amount_check check (
     (reason = 'checkin'        and amount = 30)
  or (reason = 'hint_bonus'     and amount = 10)
  or (reason = 'weekly_mission' and amount in (50, 100, 150))
  or (reason = 'town_conquest'  and amount = 100)
  or (reason = 'gacha'          and amount < 0)
  or (reason = 'login_bonus'    and amount in (10, 50))
  or (reason = 'present'        and amount between 1 and 10000)
);

alter table public.coin_ledger drop constraint if exists coin_ledger_present_ref_check;
alter table public.coin_ledger add constraint coin_ledger_present_ref_check
  check ((present_id is not null) = (reason = 'present'));

create unique index if not exists coin_ledger_user_present_uniq
  on public.coin_ledger (user_id, present_id) where present_id is not null;

-- -----------------------------------------------------------------------------
-- 3. my_notices: 出している期間のお知らせ（新しい順に 30 件）
-- -----------------------------------------------------------------------------
create or replace function public.my_notices()
returns table (notice_id bigint, title text, body text, starts_at timestamptz)
language sql
stable
security definer
set search_path = ''
as $$
  select n.notice_id, n.title, n.body, n.starts_at
    from public.notices n
   where (select auth.uid()) is not null
     and n.starts_at <= now()
     and (n.ends_at is null or n.ends_at > now())
   order by n.starts_at desc, n.notice_id desc
   limit 30;
$$;

-- -----------------------------------------------------------------------------
-- 4. my_presents: 自分宛て（全員宛てを含む）の、期限内で受け取っていないもの＋30 日以内に受け取ったもの
-- -----------------------------------------------------------------------------
create or replace function public.my_presents()
returns table (present_id bigint, title text, message text, coins integer, expires_at timestamptz, claimed boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select p.present_id, p.title, p.message, p.coins, p.expires_at, (c.present_id is not null)
    from public.presents p
    left join public.present_claims c
      on c.present_id = p.present_id and c.user_id = (select auth.uid())
   where (select auth.uid()) is not null
     and (p.user_id is null or p.user_id = (select auth.uid()))
     and p.starts_at <= now()
     and ((c.present_id is null and p.expires_at > now())
       or (c.present_id is not null and c.claimed_at > now() - interval '30 days'))
   order by p.starts_at desc, p.present_id desc
   limit 50;
$$;

-- -----------------------------------------------------------------------------
-- 5. claim_present: 受け取る（1 人 1 回）
--   返す: coins_awarded（今回もらった枚数。受け取れないときは 0）、status（ok / already / expired / not_found）
-- -----------------------------------------------------------------------------
create or replace function public.claim_present(p_present_id bigint)
returns table (coins_awarded integer, status text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_p    public.presents%rowtype;
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  select * into v_p from public.presents p
   where p.present_id = p_present_id
     and (p.user_id is null or p.user_id = v_user)
     and p.starts_at <= now();
  if not found then
    coins_awarded := 0; status := 'not_found'; return next; return;
  end if;

  -- 同じ人の同時の呼び出しを 1 つずつにする
  perform pg_advisory_xact_lock(hashtextextended('present:' || v_user::text || ':' || p_present_id::text, 0));

  if exists (select 1 from public.present_claims c where c.present_id = p_present_id and c.user_id = v_user) then
    coins_awarded := 0; status := 'already'; return next; return;
  end if;
  if v_p.expires_at <= now() then
    coins_awarded := 0; status := 'expired'; return next; return;
  end if;

  insert into public.present_claims (present_id, user_id) values (p_present_id, v_user);
  insert into public.coin_ledger (user_id, reason, amount, present_id)
  values (v_user, 'present', v_p.coins, p_present_id);

  coins_awarded := v_p.coins; status := 'ok';
  return next;
end;
$$;

revoke all on function public.my_notices() from public, anon;
grant execute on function public.my_notices() to authenticated, service_role;
revoke all on function public.my_presents() from public, anon;
grant execute on function public.my_presents() to authenticated, service_role;
revoke all on function public.claim_present(bigint) from public, anon;
grant execute on function public.claim_present(bigint) to authenticated, service_role;
